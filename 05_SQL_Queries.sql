# Database Selection
-- Select the Real Estate Analytics database for performing analysis
use real_estate_analytics;

# Query 1: Display all properties
# SELECT
-- To review the complete property listing data
select *from Property;


# Query 2: Display the property type, city, locality and price
# SELECT
-- To review the key details of each property
select
property_id,
property_type,
city,
locality,
price
from Property;


# Query 3: Display customers with budget above 10000000
# SELECT, WHERE
-- To review customers with higher purchasing capacity
select
customer_id,
customer_name,
city,
budget
from Customers
where budget > 10000000;


# Query 4: Display the 5 most expensive properties
# SELECT, ORDER BY, LIMIT
-- To compare the highest-priced properties
select
property_id,
property_type,
city,
price
from Property
order by price desc
limit 5;


# Query 5: Display property visits where customers were not interested
# SELECT, WHERE
-- To review visits that did not result in customer interest
select
visit_id,
customer_id,
property_id,
visit_date
from Property_Visits
where interested = 'No';


# Query 6: Display recently registered customers
# SELECT, WHERE, DATE
-- To review recent customer registrations
select
customer_id,
customer_name,
city,
registration_date
from Customers
where registration_date >= '2025-01-01'
order by registration_date;


# Query 7: Find total transactions and total sales
# COUNT, SUM
-- To measure the overall number of property sales and revenue generated
select
count(*) as total_transactions,
sum(sale_price) as total_sales
from Transactions;


# Query 8: Find average, minimum and maximum customer budget
# AVG, MIN, MAX
-- To understand the range of customer purchasing capacity
select
round(avg(budget),2) as average_budget,
min(budget) as minimum_budget,
max(budget) as maximum_budget
from Customers;


# Query 9: Find customer count and average budget by city
# COUNT, AVG, GROUP BY, ORDER BY
-- To compare customer volume and purchasing capacity across cities
select
city,
count(*) as total_customers,
round(avg(budget),2) as average_budget
from Customers
group by city
order by average_budget desc;


# Query 10: Find property types with more than 10 properties
# COUNT, GROUP BY, HAVING
-- To identify property categories with higher inventory
select
property_type,
count(*) as total_properties
from Property
group by property_type
having count(*) > 10;


# Query 11: Find total transactions and sales by month
# MONTH, COUNT, SUM, GROUP BY, ORDER BY
-- To compare transaction activity and sales revenue across different months
select
month(transaction_date) as transaction_month,
count(*) as total_transactions,
sum(sale_price) as total_sales
from Transactions
group by month(transaction_date)
order by transaction_month;


# Query 12: Display properties along with their agents
# SELECT, INNER JOIN
-- To connect each property with the agent responsible for it
select
p.property_id,
p.property_type,
p.city,
p.price,
a.agent_name
from Property p
inner join Agents a
on p.agent_id = a.agent_id;


# Query 13: Display customers along with their property visits
# SELECT, LEFT JOIN
-- To review customer visit activity, including customers with no visits
select
c.customer_id,
c.customer_name,
pv.property_id,
pv.visit_date,
pv.interested
from Customers c
left join Property_Visits pv
on c.customer_id = pv.customer_id;


# Query 14: Find the number of properties handled by each agent
# LEFT JOIN, COUNT, GROUP BY
-- To compare the number of properties managed by each agent
select
a.agent_name,
count(p.property_id) as total_properties
from Agents a
left join Property p
on a.agent_id = p.agent_id
group by a.agent_id, a.agent_name;


# Query 15: Display customers with their transaction details
# INNER JOIN, SELECT
-- To connect customers with their property purchase transactions
select
    c.customer_id,
    c.customer_name,
    t.transaction_id,
    t.property_id,
    t.transaction_date,
    t.sale_price
from Customers c
inner join Transactions t
on c.customer_id = t.customer_id;


# Query 16: Display properties with agent and customer details
# MULTIPLE JOIN, SELECT
-- To connect properties with the agent managing them and the customer who purchased them
select
p.property_id,
p.property_type,
p.city,
a.agent_name,
c.customer_name,
t.transaction_date,
t.sale_price
from Property p
inner join Agents a
on p.agent_id = a.agent_id
inner join Transactions t
on p.property_id = t.property_id
inner join Customers c
on t.customer_id = c.customer_id;


# Query 17: Find total sales generated by each agent
# INNER JOIN, SUM, COUNT, GROUP BY
-- To compare the sales performance of different agents
select
a.agent_name,
count(t.transaction_id) as total_transactions,
sum(t.sale_price) as total_sales
from Agents a
inner join Property p
on a.agent_id = p.agent_id
inner join Transactions t
on p.property_id = t.property_id
group by a.agent_id, a.agent_name;


# Query 18: Display customers who visited a property and later purchased it
# MULTIPLE JOIN, WHERE
-- To identify customers whose property visit resulted in a purchase
select
c.customer_name,
pv.property_id,
pv.visit_date,
t.transaction_date,
t.sale_price
from Customers c
inner join Property_Visits pv
on c.customer_id = pv.customer_id
inner join Transactions t
on pv.customer_id = t.customer_id
and pv.property_id = t.property_id
where t.transaction_date >= pv.visit_date;


# Query 19: Find the number of visits received by each property
# LEFT JOIN, COUNT, GROUP BY
-- To identify properties receiving the highest customer attention
select
p.property_id,
p.property_type,
p.city,
count(pv.visit_id) as total_visits
from Property p
left join Property_Visits pv
on p.property_id = pv.property_id
group by p.property_id, p.property_type, p.city;


# Query 20: Find customers who visited properties in Mumbai
# IN, SUBQUERY, WHERE
-- To find customers who visited properties located in Mumbai
select
customer_id,
customer_name
from Customers
where customer_id in (
    select customer_id
    from Property_Visits
    where property_id in (
        select property_id
        from Property
        where city = 'Mumbai'
    )
);


# Query 21: Find customers who have not visited any property
# NOT IN, SUBQUERY
-- To find customers without any recorded property visits
select
customer_id,
customer_name,
city
from Customers
where customer_id not in (
    select customer_id
    from Property_Visits
);


# Query 22: Find the most expensive property among properties above average price
# NESTED SUBQUERY, MAX, AVG
-- To find the highest-priced property from the above-average price segment
select
property_id,
property_type,
city,
price
from Property
where price = (
    select max(price)
    from Property
    where price > (
        select avg(price)
        from Property
    )
);


# Query 23: Find customers whose budget is higher than the average property price
# SUBQUERY, AVG, WHERE
-- To find customers whose purchasing capacity is higher than the average property price
select
customer_id,
customer_name,
city,
budget
from Customers
where budget > (
    select avg(price)
    from Property
);


# Query 24: Create a view for available properties
# CREATE VIEW, SELECT, WHERE
-- To create a view for properties currently available for sale
create view Available_Properties as
select
property_id,
property_type,
city,
price,
bedrooms
from Property
where status = 'Available';


# Query 25: Display available properties
# SELECT, VIEW
-- To review the data stored in the Available_Properties view
select * from Available_Properties;


# Query 26: Find the number of available properties by city
# COUNT, GROUP BY, VIEW, ORDER BY
-- To compare available property inventory across different cities
select
city,
count(*) as available_properties
from Available_Properties
group by city;


# Query 27: Create a view for agent sales performance
# CREATE VIEW, INNER JOIN, SUM, COUNT, GROUP BY
-- To create a view for comparing agent sales performance
create view Agent_Performance as
select
a.agent_id,
a.agent_name,
count(t.transaction_id) as total_transactions,
sum(t.sale_price) as total_sales
from Agents a
inner join Property p
on a.agent_id = p.agent_id
inner join Transactions t
on p.property_id = t.property_id
group by a.agent_id, a.agent_name;


# Query 28: Display agent performance
# SELECT, VIEW, ORDER BY
-- To review and compare sales performance of each agent
select *
from Agent_Performance
order by total_sales desc;


# Query 29: Find agents with total sales above 1 crore
# SELECT, VIEW, WHERE
-- To find agents who generated more than 1 crore in sales
select
agent_name,
total_transactions,
total_sales
from Agent_Performance
where total_sales > 10000000;


# Query 30: Rank properties based on price
# RANK, DENSE RANK, OVER, ORDER BY
-- To rank properties from highest to lowest price
select
property_id,
property_type,
city,
price,
rank() over(order by price desc) as price_rank,
dense_rank() over(order by price desc) as price_dense_rank
from Property;


# Query 31: Find the top 2 most expensive properties in each city
# RANK, OVER, PARTITION BY, ORDER BY
-- To find the highest-priced properties within each city
select *
from (
    select
	property_id,
	property_type,
	city,
	price,
	rank() over( partition by city order by price desc ) as city_rank
    from Property
) as ranked_properties
where city_rank <= 2;


# Query 32: Assign a sequence number to each customer's property visits
# ROW_NUMBER, OVER, PARTITION BY, ORDER BY
-- To track the order of property visits made by each customer
select
customer_id,
property_id,
visit_id,
visit_date,
row_number() over( partition by customer_id order by visit_date ) as visit_number
from Property_Visits;


# Query 33: Compare property price with city average
# AVG, OVER, PARTITION BY, Arithmetic, IF
-- To compare each property's price with the average price of its city
select
property_id,
property_type,
city,
price,
round( avg(price) over(partition by city),2 ) as city_average_price,
if(
        price > avg(price) over(partition by city), 'Higher',
        if(
            price < avg(price) over(partition by city), 'Lower',
		'Equal')
    ) as price_comparison
from Property;


# Query 40: Classify customers based on their budget
# IF
-- To classify customers based on their purchasing capacity
select
customer_id,
customer_name,
city,
budget,
if(budget >= 10000000, 'High', 'Regular') as budget_category
from Customers;


# Query 41: Rank and classify agents based on total sales
# DENSE RANK, OVER, SUM, GROUP BY, IF, MULTIPLE JOINS
-- To rank agents by total sales and classify their performance
select
agent_name,
total_sales,
dense_rank() over(order by total_sales desc) as sales_rank,
    if(
        dense_rank() over(order by total_sales desc) <= 3, 'Top Performer',
        'Other'
    ) as performance
from (
    select
	a.agent_name,
	sum(t.sale_price) as total_sales
    from Agents a
    inner join Property p
    on a.agent_id = p.agent_id
    inner join Transactions t
    on p.property_id = t.property_id
    group by a.agent_id, a.agent_name
) as agent_sales;


# Query 42: Find the number of days between property visit and purchase
# DATEDIFF, INNER JOIN, GROUP BY, MIN
-- To measure the time taken by customers to purchase a property after visiting it
select
c.customer_id,
c.customer_name,
pv.property_id,
min(pv.visit_date) as visit_date,   -- MIN() is used to consider the customer's first visit before purchase
t.transaction_date as purchase_date,
datediff(
        t.transaction_date,
        min(pv.visit_date)
    ) as days_to_purchase
from Customers c
inner join Property_Visits pv
on c.customer_id = pv.customer_id
inner join Transactions t
on pv.customer_id = t.customer_id    -- To connect the property visit with the customer's purchase
and pv.property_id = t.property_id   -- To ensure the purchase is for the same property that was visited
group by
    c.customer_id,
    c.customer_name,
    pv.property_id,
    t.transaction_date
order by days_to_purchase;


# Query 43: Display customer feedback with a default value
# COALESCE
-- To display feedback and show 'No Feedback' when a visit has no feedback
select
visit_id,
customer_id,
property_id,
coalesce(feedback, 'No Feedback') as feedback
from Property_Visits;


# Query 44: Round up the average property price
# CEIL, AVG
-- To round the average property price up to the next whole number
select
avg(price) as average_price,
ceil(avg(price)) as rounded_average_price
from Property;


# Query 45: Round down customer budgets to the nearest lakh
# FLOOR, Arithmetic
-- To group customer budgets into whole-lakh values
select
customer_id,
customer_name,
budget,
floor(budget / 100000) * 100000 as rounded_budget  -- divided the budget by 1 lakh, used FLOOR() to remove the decimal part, and multiplied it back by 1 lakh
from Customers;


# Query 46: Categorize properties based on price
# CASE, SELECT
-- To classify properties into different price categories
select
property_id,
property_type,
price,
case
	when price >= 10000000 then 'Premium'
	when price >= 5000000 then 'Mid Range'
	else 'Standard'
end as price_category
from Property;


# Query 47: Compare similar properties with different prices
# SELF JOIN, JOIN, WHERE
-- To identify similar properties in the same city and compare their prices
select
p1.property_id as Property_1,
p2.property_id as Property_2,
p1.city,
p1.property_type,
p1.bedrooms,
p1.price as Price_1,
p2.price as Price_2
from Property p1
join Property p2
on p1.city = p2.city
and p1.property_type = p2.property_type
and p1.bedrooms = p2.bedrooms
and p1.property_id < p2.property_id
where p1.price <> p2.price;